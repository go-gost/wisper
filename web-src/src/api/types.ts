/** One peer's traffic during the tunnel's current run, plus the p2p host's
 *  live diagnostic for it. The diagnostic fields are absent until the peer has
 *  a session (and on an older p2p that does not report them). */
export interface PeerStats {
  key: string;
  alias?: string;
  /** Where this peer's traffic goes now: 'direct' or 'derp'; absent when it
   *  has no session at all. */
  transport?: string;
  /** Host-wide cause when it outranks the peer's own round ('no-candidates',
   *  'stun-unreachable', 'disabled'); verbatim p2p wire values. */
  reason?: string;
  /** The punch state machine: 'none' | 'attempting' | 'up' | 'backoff'. */
  state?: string;
  /** A punch round has failed (sticky); independent of the current state. */
  failed?: boolean;
  /** The last punch failure's reason (absent after a success). */
  last_error?: string;
  /** The endpoint dialled for the direct path (absent until a round dials). */
  peer_addr?: string;
  /** How many candidates the peer announced. */
  candidates?: number;
  /** The peer's advertised capabilities ('ipv6', 'tightKeepalive'). */
  caps?: string[];
  /** How long the live direct session has been up (0 when none). */
  session_age_ms?: number;
  /** How long since the last frame from the peer. */
  last_recv_age_ms?: number;
  /** The peer's recent punch history: short lines, oldest first (newest kept),
   *  capped by the p2p host's ring. */
  trace?: string[];
  /** The LANs this peer holds on the hub's network — the CIDRs it claimed.
   *  Absent when it holds none (and on an object that has no device network). */
  lan?: string[];
  current_conns: number;
  total_conns: number;
  input_bytes: number;
  output_bytes: number;
  input_rate_bytes: number;
  output_rate_bytes: number;
}

/** One recorded occurrence in a tunnel's, entrypoint's, or the host's history.
 *  Named WisperEvent rather than Event: the DOM's global Event type would be
 *  shadowed in every module that imports this. */
export interface WisperEvent {
  time: string;
  level: 'info' | 'warn' | 'error';
  message: string;
  /** Run length of a coalesced repeat (1 for a one-off). A pre-count event
   *  carries 0 and should be read as 1. */
  count?: number;
}

/** One LAN route a tun hub installed: the CIDR, who put it there (a spoke's
 *  key, or 'static' for the hub's own config), the member that carries it, and
 *  the members allowed to use it (absent = all of them). */
export interface LANRoute {
  prefix: string;
  origin: string;
  peer: string;
  allow?: string[];
}

/** One claim a tun hub turned down: the CIDR, the spoke that asked, the RIB's
 *  reason code, the sentence an operator reads, and when. A refusal is never
 *  revoked and its prefix never reaches the routes table, which is why the two
 *  lists are read together. */
export interface LANRefusal {
  prefix: string;
  peer: string;
  reason: string;
  detail?: string;
  at: string;
}

/** A tun hub's LAN routing, as one read of its RIB: the installed table, each
 *  spoke's claim of it, and what was refused. Only a running hub reports one,
 *  so every other object — and a hub whose control channel never opened —
 *  leaves the field absent. */
export interface TunnelLAN {
  routes: LANRoute[];
  claims: Record<string, { prefixes: string[]; allow?: string[] }>;
  rejected?: LANRefusal[];
}

