// ─── Tunnel ──────────────────────────────────────────────────────────────────

/** One p2p allowlist entry: the key is the credential, the alias its display
 *  name (generated by the backend when not given). */
export interface Peer {
  key: string;
  alias?: string;
  /** Switched off: the peer keeps its place on the list but gets no route, so
   *  its new streams are closed while established ones drain. */
  disabled?: boolean;
  /** The address this peer may claim on the hub's device network (host
   *  addresses, comma-separated; never a prefix). Absent when the row holds
   *  none — the hub allocates one on the next save. A p2p tunnel has no device
   *  network, so its rows never carry it. */
  ip?: string;
}

export interface TunnelOptions {
  prefix?: string;
  hostname: string;
  username: string;
  password: string;
  basic_auth: boolean;
  enableTLS: boolean;
  rewriteHost: boolean;
  file_upload: boolean;
  keepalive: boolean;
  ttl: number;
  record_mode: string;
  /** Remote peer's base64 public key (p2p entrypoints). */
  peer?: string;
  /** Inbound allowlist: the peers whose streams reach this p2p tunnel. Empty = unreachable. */
  peers?: Peer[];
  /** tun device address (CIDR, comma-separated for several). */
  net?: string;
  /** tun device MTU (absent = the implementation default, 1420). */
  mtu?: number;
  /** tun device name (absent = kernel-chosen). */
  device_name?: string;
  /** Subnets routed through the device, comma-separated "cidr [gw]" pairs. */
  routes?: string;
  /** The device's DNS servers, comma-separated. */
  dns?: string;
  /** Hub-side LAN subnets shared with peers (comma-separated CIDRs, empty disables). */
  share_lan?: string;
  /** Sharing backend: 'auto' (default), 'kernel', or 'userspace'. */
  share_mode?: string;
}

