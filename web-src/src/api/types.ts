// ─── Inspector ───────────────────────────────────────────────────────────

/** HTTP header map, as serialized from Go's `http.Header` (`map[string][]string`). */
export type HttpHeaders = Record<string, string[]>;

export interface HttpRecord {
  host: string;
  method: string;
  proto: string;
  scheme: string;
  uri: string;
  statusCode: number;
  request: { header: HttpHeaders | null; body: string | null };   // null when from list (excluded via projection)
  response: { header: HttpHeaders | null; body: string | null };  // null when from list
}

export interface WsRecord {
  from: string;
  fin: boolean;
  rsv1: boolean;
  rsv2: boolean;
  rsv3: boolean;
  opcode: number;
  masked: boolean;
  maskKey?: number;
  length: number;
  payload: string | null;  // null when from list
}

export interface InspectorRecord {
  id?: string;          // MongoDB ObjectID hex — set from list cursor & detail endpoint
  node?: string;
  service: string;
  network: string;
  remote: string;
  local: string;
  host: string;
  dst: string;
  proto?: string;
  clientIP: string;
  clientID?: string;
  http?: HttpRecord;
  websocket?: WsRecord;
  route?: string;
  inputBytes: number;
  outputBytes: number;
  redirect?: string;
  err?: string;
  sid: string;
  duration: number;
  time: string;
}

export interface InspectorQueryResponse {
  code: number;
  data: {
    list: InspectorRecord[];
    before?: string;
    after?: string;
  };
  msg: string;
  error?: string;
}

